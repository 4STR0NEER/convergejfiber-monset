const cell = 'border-b border-zinc-200 py-1.5 pr-2'

export function RecommendationDoc() {
  const { period = '' } = useParams()
  const { snap, can } = useData()
  const data = useCloseData(period)
  const { close } = useClose(period)
  const charged = (id: string) => !close.waived[id]
  if (!can('close.run')) return <p className="mx-auto max-w-xl px-6 py-24 text-muted">The LD recommendation is an internal Converge-J Fiber document. Your claim notice is under Month-End Close, step Day 6-10.</p>
  const grand = data.recs.reduce((a, r) => a + r.items.filter(i => charged(i.poId)).reduce((x, i) => x + i.amount, 0), 0)
  return (
    <Letter period={period} title={`Liquidated damages recommendation, ${periodName(period)}`}>
      <p className="mt-3">To: Project Management Office<br />From: Backbone Build</p>
      <p className="mt-3">Following the fallout list and gap analyses for {periodName(period)}, Backbone Build recommends the liquidated damages below. Only delay attributable to the contractor is charged; delays from excused causes (OSI delivery, DPWH, LGU policies, permits outside the contractor's control and similar) have extended the target dates and are not charged.</p>
      {data.recs.map(r => (
        <section key={r.contractorId} className="mt-6 break-inside-avoid">
          <h2 className="font-semibold">{snap.contractors.find(c => c.id === r.contractorId)?.name}</h2>
          <table className="mt-2 w-full text-left text-[12.5px]">
            <thead><tr>{['PO / WO', 'Cost of works', 'Days', 'Weeks', 'LD'].map(h => <th key={h} className={`${cell} font-medium text-zinc-500`}>{h}</th>)}</tr></thead>
            <tbody>
              {r.items.map(i => {
                const ev = data.evals.find(e => e.po.id === i.poId)!
                return (
                  <tr key={i.poId} className={charged(i.poId) ? '' : 'text-zinc-400'}>
                    <td className={cell}>{i.poId}{!charged(i.poId) && <span className="block text-[11px]">Waived: {close.waived[i.poId]}</span>}</td>
                    <td className={cell}>{peso(ev.po.costOfWorks)}</td>
                    <td className={cell}>{i.lateDays}</td>
                    <td className={cell}>{i.weeks}</td>
                    <td className={`${cell} text-right`}>{charged(i.poId) ? peso(i.amount) : '–'}</td>
                  </tr>
                )
              })}
            </tbody>
          </table>
        </section>
      ))}
      <p className="mt-6 flex justify-between border-t-2 border-zinc-800 pt-2 font-semibold"><span>Total recommended</span><span>{peso(grand)}</span></p>
      <p className="mt-10">Prepared by: ______________________<br /><span className="text-xs text-zinc-500">Backbone Project Manager</span></p>
    </Letter>
  )
}

export function NoticeDoc() {
  const { period = '', contractorId = '' } = useParams()
  const { snap } = useData()
  const data = useCloseData(period)
  const { close } = useClose(period)
  const c = snap.contractors.find(x => x.id === contractorId)
  const rec = data.recs.find(r => r.contractorId === contractorId)
  if (!c || !rec) return <p className="p-8 text-muted">No LD claim for this contractor in {periodName(period)}.</p>
  const items = rec.items.filter(i => !close.waived[i.poId])
  const total = items.reduce((a, i) => a + i.amount, 0)
  return (
    <Letter period={period} title="Notice of liquidated damages claim">
      <p className="mt-3">To: <span className="font-semibold">{c.name}</span><br />Re: Liquidated damages for delay as of {fmtDate(monthEnd(period))}</p>
      <p className="mt-3">This notice informs you that the works under the purchase / work orders below were not completed by the Provisional Acceptance Test (PAT) dates in the signed Project Timelines, after allowing every day of excused delay. Liquidated damages are assessed at 0.5% of the cost of works for each calendar week of delay or portion of a week, up to 50% of the cost of works.</p>
      <table className="mt-5 w-full text-left text-[12.5px]">
        <thead><tr>{['PO / WO', 'PTL target', 'Extended target', 'Status', 'Days', 'LD'].map(h => <th key={h} className={`${cell} font-medium text-zinc-500`}>{h}</th>)}</tr></thead>
        <tbody>
          {items.map(i => {
            const ev = data.evals.find(e => e.po.id === i.poId)!
            return (
              <tr key={i.poId}>
                <td className={cell}>{i.poId}<span className="block text-[11px] text-zinc-500">{ev.po.title}</span></td>
                <td className={cell}>{fmtDate(currentPtl(ev.po).targetPat)}</td>
                <td className={cell}>{fmtDate(ev.effectiveTarget)}</td>
                <td className={cell}>{ev.ld.clockStopped ? `PAT ${fmtDate(ev.po.patDate!)}` : 'Open, still accruing'}</td>
                <td className={cell}>{i.lateDays}</td>
                <td className={`${cell} text-right`}>{peso(i.amount)}</td>
              </tr>
            )
          })}
        </tbody>
      </table>
      <p className="mt-4 flex justify-between border-t-2 border-zinc-800 pt-2 font-semibold"><span>Total liquidated damages claimed</span><span>{peso(total)}</span></p>
      <p className="mt-5">Please acknowledge receipt of this notice by signing below and returning a copy to the Project Management Office. Any dispute, with supporting documents, should be raised within the period set in the contract.</p>
      <div className="mt-10 grid grid-cols-2 gap-10">
        <p>______________________<br /><span className="text-xs text-zinc-500">Project Management Office</span></p>
        <p>______________________<br /><span className="text-xs text-zinc-500">Received and acknowledged for {c.name} (name, date)</span></p>
      </div>
    </Letter>
  )
}
